export type Lang = "es" | "en";
const dicts = { es, en };
const initial = (): Lang => {
  try {
    const saved = localStorage.getItem("lang");
    if (saved === "es" || saved === "en") return saved;
  } catch {}
  return navigator.language.startsWith("es") ? "es" : "en";
};

const Ctx = createContext<{ t: Dict; lang: Lang; setLang: (l: Lang) => void }>(null!);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initial);
  const setLang = (l: Lang) => {
    setLangState(l);
    document.documentElement.lang = l;
    try {
      localStorage.setItem("lang", l);
    } catch {}
  };
  return <Ctx.Provider value={{ t: dicts[lang], lang, setLang }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
export const useT = () => useContext(Ctx).t;

/** Locale para Intl: español rioplatense o inglés, respetando la región del navegador si coincide el idioma. */
export const useLocale = () => {
  const { lang } = useI18n();
  return navigator.language.startsWith(lang) ? navigator.language : lang;
};

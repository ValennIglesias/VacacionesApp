export const avatarUrl = (file: string) => `/avatars/3d/${file}.png`;

/** Solo se muestran/aceptan avatares de la galería o la foto de Google: nada de URLs arbitrarias. */
export const isSafeAvatar = (url: string | null | undefined): url is string =>
  !!url && /^(\/avatars\/3d\/[a-z-]+\.png|https:\/\/lh3\.googleusercontent\.com\/.+)$/.test(url);

export const isGalleryAvatar = (url: string) => url.startsWith("/avatars/");
